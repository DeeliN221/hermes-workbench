/** All-profile home, durable display-name UI, default compose, and scoped writes. */
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createMockHost } from './mock-host.mjs';
const host = await createMockHost();
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE_PATH || undefined });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [], writes = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('403')) errors.push(message.text()); });
  let dataState = 'ready';
  await page.route('**/api/plugins/workbench/codex/sessions?*', async route => {
    if (dataState === 'denied') return route.fulfill({ status: 403, json: { detail: 'Forbidden' } });
    const response = await route.fetch();
    const data = await response.json();
    await route.fulfill({ json: { ...data, items: (data.items || []).map(row => ({ ...row, groupId: 'preview-project-1' })) } });
  });
  await page.route('**/api/plugins/workbench/profile-names', async route => {
    if (dataState === 'empty') return route.fulfill({ json: { profiles: [] } });
    await route.continue();
  });
  page.on('request', request => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) writes.push({ url: request.url(), method: request.method(), body: request.postDataJSON() }); });
  const aliases = {};
  await page.route('**/api/plugins/workbench/profile-display*', async route => {
    if (route.request().method() === 'PUT') aliases[new URL(route.request().url()).searchParams.get('profile')] = route.request().postDataJSON().display_name;
    await route.fulfill({ json: { aliases } });
  });
  await page.goto(host.origin + '/profiles?profile=writer');
  const card = page.locator('[data-profile="default"]');
  await card.locator('.workbench-profile-display input').fill('Main Agent');
  await card.getByRole('button', { name: 'Save display name' }).click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('[data-profile="default"] h2')?.textContent.includes('Main Agent'));
  await page.goto(host.origin + '/sessions?profile=writer');
  await page.locator('.workbench-home-project').first().waitFor();
  assert.match(await page.locator('label[for="home-message"]').textContent(), /Main Agent/);
  assert.equal(await page.locator('.workbench-home-project').count(), 8);
  assert.ok((await page.locator('.workbench-home-project').allTextContents()).some(text => text.includes('writer')));
  assert.equal(writes.filter(w => /session/.test(w.url)).length, 0, 'Loading aggregate home must be read-only');
  const cards = page.locator('.workbench-home-grid a[href*="profile=writer"][href*="session="]');
  assert.ok(await cards.count());
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/home-desktop.png` });
  await page.locator('.workbench-home-project').filter({ hasText: 'writer' }).first().locator('summary').click();
  await cards.first().click();
  await page.waitForURL(url => url.pathname === '/chat' && url.searchParams.get('profile') === 'writer');
  await page.locator('.codex-session-rename').first().click();
  const dialog = page.locator('dialog[open]');
  await dialog.locator('input[name="session-title"]').fill('Writer conversation');
  await dialog.locator('.codex-navigation-dialog-actions button.is-primary').click();
  await page.waitForFunction(() => document.querySelector('.codex-center-title')?.textContent.includes('Writer conversation'));
  assert.ok(writes.some(w => w.method === 'PATCH' && w.url.includes('profile=writer')));
  assert.ok(!writes.some(w => w.method === 'PATCH' && w.url.includes('profile=default')));
  await page.goto(host.origin + '/sessions?profile=writer');
  await page.locator('#home-message').fill('A task for the main agent');
  await page.locator('.workbench-home-compose button[type="submit"]').click();
  await page.waitForURL(url => url.pathname === '/chat' && url.searchParams.get('profile') === 'default');
  const send = writes.find(w => w.body?.text === 'A task for the main agent');
  assert.equal(send.body.profile, 'default'); assert.match(send.url, /profile=default/);
  const create = writes.find(w => w.method === 'POST' && new URL(w.url).pathname.endsWith('/codex/sessions'));
  assert.equal(create.body.profile, 'default');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(host.origin + '/sessions?profile=writer');
  await page.locator('.workbench-home-project').first().waitFor();
  assert.ok(await page.locator('.workbench-home-card-meta').first().isVisible());
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No mobile horizontal overflow');
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/home-mobile.png` });
  await page.getByRole('link', { name: /New session.*Main Agent/ }).click();
  await page.waitForURL(url => url.pathname === '/chat' && url.searchParams.get('profile') === 'default' && url.searchParams.get('new') === '1');
  dataState = 'denied';
  await page.goto(host.origin + '/sessions?profile=default');
  await page.getByRole('alert').filter({ hasText: 'failed to load' }).first().waitFor();
  dataState = 'empty';
  await page.goto(host.origin + '/sessions?profile=default');
  await page.getByText('No sessions yet. Start a conversation.').waitFor();
  assert.equal(await page.locator('.workbench-home-project').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: display-name reload, read-only all-profile projects/sessions, scoped open/rename, default send/new, desktop/mobile, denied/empty states');
} finally { await browser.close(); await host.close(); }
